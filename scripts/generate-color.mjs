import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokenPath = path.join(root, 'design-tokens/tokens/color.json');
const outputPath = path.join(root, 'design-tokens/generated/css/color.css');
const tokens = JSON.parse(fs.readFileSync(tokenPath, 'utf8'));

function luminance(hex) {
  const rgb = hex.replace('#', '').match(/.{2}/g).map((part) => parseInt(part, 16) / 255);
  const linear = rgb.map((v) => v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
  return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2];
}
function contrast(foreground, background) {
  const a = luminance(foreground);
  const b = luminance(background);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}
function checkPair(label, foreground, background, minimum = 4.5) {
  const ratio = contrast(foreground, background);
  console.log(`${ratio >= minimum ? 'PASS' : 'FAIL'} ${label}: ${ratio.toFixed(2)}:1 (minimum ${minimum}:1)`);
  if (ratio < minimum) throw new Error(`${label} contrast ${ratio.toFixed(2)}:1 is below ${minimum}:1`);
}
function validateHex(value, label) {
  if (typeof value !== 'string' || !/^#[0-9a-f]{6}$/i.test(value)) {
    throw new Error(`${label} must be a six-digit hex color; received ${String(value)}`);
  }
}
for (const [name, value] of Object.entries(tokens.palette)) validateHex(value, `palette.${name}`);
for (const theme of ['light', 'dark']) {
  const values = tokens.semantic[theme];
  for (const [name, value] of Object.entries(values)) validateHex(value, `semantic.${theme}.${name}`);
  checkPair(`${theme} primary text / canvas`, values.textPrimary, values.canvas);
  checkPair(`${theme} secondary text / canvas`, values.textSecondary, values.canvas);
  checkPair(`${theme} muted text / canvas`, values.textMuted, values.canvas);
  checkPair(`${theme} primary action label`, values.actionPrimaryText, values.actionPrimary);
  checkPair(`${theme} primary action hover label`, values.actionPrimaryText, values.actionPrimaryHover);
  checkPair(`${theme} secondary action label`, values.actionSecondaryText, values.actionSecondary);
  checkPair(`${theme} link / canvas`, values.link, values.canvas);
  checkPair(`${theme} focus / canvas`, values.focus, values.canvas, 3);
  checkPair(`${theme} disabled label / disabled surface`, values.disabledText, values.disabledSurface);
  checkPair(`${theme} success / surface`, values.success, values.surface);
  checkPair(`${theme} warning / surface`, values.warning, values.surface);
  checkPair(`${theme} danger / surface`, values.danger, values.surface);
  checkPair(`${theme} info / surface`, values.info, values.surface);
}
checkPair('orange variant label', tokens.variants.actionOrange.foreground, tokens.variants.actionOrange.background);
checkPair('deep orange variant label', tokens.variants.actionOrangeDeep.foreground, tokens.variants.actionOrangeDeep.background);

const kebab = (s) => s.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
let css = '/* Generated by scripts/generate-color.mjs. Edit color.json, not this file. */\n:root {\n';
for (const [name, value] of Object.entries(tokens.palette)) css += `  --juf-palette-${kebab(name)}: ${value};\n`;
css += '}\n\n:root,\n[data-juf-theme="light"] {\n';
for (const [name, value] of Object.entries(tokens.semantic.light)) css += `  --juf-color-${kebab(name)}: ${value};\n`;
css += '}\n\n[data-juf-theme="dark"] {\n';
for (const [name, value] of Object.entries(tokens.semantic.dark)) css += `  --juf-color-${kebab(name)}: ${value};\n`;
css += '}\n\n:root {\n';
for (const [name, value] of Object.entries(tokens.gradients)) css += `  --juf-gradient-${kebab(name)}: ${value};\n`;
for (const [name, variant] of Object.entries(tokens.variants)) {
  css += `  --juf-${kebab(name)}-background: ${variant.background};\n`;
  css += `  --juf-${kebab(name)}-foreground: ${variant.foreground};\n`;
}
css += '}\n';

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== css) {
    console.error('Generated color CSS is missing or out of date. Run node scripts/generate-color.mjs.');
    process.exitCode = 1;
  } else {
    console.log('Color tokens are valid; contrast checks pass; generated CSS is up to date.');
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, css, 'utf8');
  console.log(`Generated ${path.relative(root, outputPath)}`);
}
